pub const RANK_PERSON: u8 = 0;
pub const RANK_INFERRED: u8 = 1;
pub const RANK_CONFIRMED: u8 = 2;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tier {
    Person,
    Inferred,
    Confirmed,
}

impl Tier {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Person => "person",
            Self::Inferred => "inferred",
            Self::Confirmed => "confirmed",
        }
    }

    pub fn parse(text: &str) -> Option<Self> {
        match text {
            "person" => Some(Self::Person),
            "inferred" => Some(Self::Inferred),
            "confirmed" => Some(Self::Confirmed),
            _ => None,
        }
    }

    pub fn rank(self) -> u8 {
        match self {
            Self::Person => RANK_PERSON,
            Self::Inferred => RANK_INFERRED,
            Self::Confirmed => RANK_CONFIRMED,
        }
    }
}

