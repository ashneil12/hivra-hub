import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
const bundle = resolve(process.argv[2] || "target/release/bundle/macos/MonoCode Test.app");
if (!existsSync(bundle)) throw new Error(`No test bundle: ${bundle}`);
const read = (field) => execFileSync("/usr/libexec/PlistBuddy", ["-c", `Print :${field}`, `${bundle}/Contents/Info.plist`], { encoding: "utf8" }).trim();
if (read("CFBundleIdentifier") !== "com.ash.monocode-hub.sandbox") throw new Error("Refusing: test copy shares an app identity");
if (read("CFBundleName") !== "MonoCode Test") throw new Error("Refusing: unexpected test app name");
console.log(`Verified isolated app: ${bundle}`);
console.log("Own database, webview storage, Mono files and model-key service. Live harness bridge disabled.");
